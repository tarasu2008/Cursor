    fun fix(word: String): String? = fixes[word.lowercase()]

    /** Safe to apply when the user taps space. Long expansions stay as chips only. */
    fun auto(word: String): String? {
        val replacement = fix(word) ?: return null
        if (replacement.length > 28) return null
        if (replacement.count { it == ' ' } > 2) return null
        return replacement
    }
